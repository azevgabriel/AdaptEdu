import { describe, it, expect, vi, beforeEach } from "vitest";
import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { fakerPT_BR as faker } from "@faker-js/faker";
import { Header } from "./index";

describe("Header Component", () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it("renders the brand logo and default section title in Portuguese", () => {
    render(<Header />);

    // Brand link with accessible name
    expect(
      screen.getByRole("link", { name: /adaptEdu - início da minha sala/i })
    ).toBeInTheDocument();

    // Default section badge
    expect(screen.getByText("Minha Sala")).toBeInTheDocument();
  });

  it("renders custom section name when provided and adjusts active link styling", async () => {
    const user = userEvent.setup();
    const customSection = "Planos de Aula Adaptados";
    render(<Header sectionName={customSection} />);

    expect(screen.getByText(customSection)).toBeInTheDocument();

    // Open menu to test menu item active condition when sectionName !== "Minha Sala"
    await user.click(screen.getByRole("button", { name: /menu do usuário/i }));
    const minhaSalaItem = screen.getByRole("menuitem", { name: /^minha sala$/i });
    expect(minhaSalaItem).not.toHaveClass("menuItemActive");
  });

  it("handles single-word names and empty fallback initials", () => {
    const { unmount } = render(
      <Header teacher={{ name: "Joana", email: "j@escola.br", role: "Prof", school: "E.E." }} />
    );
    expect(screen.getByText("JO")).toBeInTheDocument();
    unmount();

    render(
      <Header teacher={{ name: "", email: "p@escola.br", role: "Prof", school: "E.E." }} />
    );
    expect(screen.getByText("ED")).toBeInTheDocument();
  });

  it("displays synthetic teacher profile data generated by Faker", () => {
    const mockTeacher = {
      name: `Profª. ${faker.person.fullName()}`,
      email: faker.internet.email().toLowerCase(),
      role: "Especialista em Educação Especial",
      school: `E.E. ${faker.person.lastName()} • Fundamental II`,
      avatarUrl: faker.image.avatar(),
    };

    render(<Header teacher={mockTeacher} />);

    expect(screen.getByText(mockTeacher.name)).toBeInTheDocument();
    expect(screen.getByText(mockTeacher.role)).toBeInTheDocument();
    expect(
      screen.getByRole("button", { name: new RegExp(mockTeacher.name, "i") })
    ).toBeInTheDocument();
  });

  it("opens and closes dropdown menu upon button click", async () => {
    const user = userEvent.setup();
    render(<Header />);

    const menuButton = screen.getByRole("button", { name: /menu do usuário/i });
    expect(menuButton).toHaveAttribute("aria-expanded", "false");

    // Click to open
    await user.click(menuButton);
    expect(menuButton).toHaveAttribute("aria-expanded", "true");

    const menu = screen.getByRole("menu", {
      name: /opções de navegação do professor/i,
    });
    expect(menu).toBeInTheDocument();

    // Verify navigation options rendered in PT-BR
    expect(
      screen.getByRole("menuitem", { name: /planos de aula adaptados/i })
    ).toBeInTheDocument();
    expect(
      screen.getByRole("menuitem", { name: /estudantes & adaptações/i })
    ).toBeInTheDocument();
    expect(
      screen.getByRole("menuitem", { name: /configurações/i })
    ).toBeInTheDocument();

    // Click again to close
    await user.click(menuButton);
    expect(menuButton).toHaveAttribute("aria-expanded", "false");
  });

  it("closes dropdown menu when Escape key is pressed", async () => {
    const user = userEvent.setup();
    render(<Header />);

    const menuButton = screen.getByRole("button", { name: /menu do usuário/i });
    await user.click(menuButton);
    expect(screen.getByRole("menu")).toBeInTheDocument();

    await user.keyboard("{Escape}");
    expect(screen.queryByRole("menu")).not.toBeInTheDocument();
  });

  it("triggers onLogout callback when logout button is clicked", async () => {
    const user = userEvent.setup();
    const handleLogout = vi.fn();

    render(<Header onLogout={handleLogout} />);

    // Open menu
    await user.click(screen.getByRole("button", { name: /menu do usuário/i }));

    // Click logout
    const logoutButton = screen.getByRole("menuitem", { name: /sair da conta/i });
    await user.click(logoutButton);

    expect(handleLogout).toHaveBeenCalledTimes(1);
    expect(screen.queryByRole("menu")).not.toBeInTheDocument();
  });

  it("navigates to '/' when logout button is clicked and no custom onLogout is provided", async () => {
    const user = userEvent.setup();
    render(<Header />);

    await user.click(screen.getByRole("button", { name: /menu do usuário/i }));

    const logoutButton = screen.getByRole("menuitem", { name: /sair da conta/i });
    await user.click(logoutButton);

    expect(screen.queryByRole("menu")).not.toBeInTheDocument();
  });

  it("closes dropdown menu when clicking outside of the menu and button", async () => {
    const user = userEvent.setup();
    render(
      <div>
        <div data-testid="outside-area">Outside</div>
        <Header />
      </div>
    );

    const menuButton = screen.getByRole("button", { name: /menu do usuário/i });
    await user.click(menuButton);
    expect(screen.getByRole("menu")).toBeInTheDocument();

    await user.click(screen.getByTestId("outside-area"));
    expect(screen.queryByRole("menu")).not.toBeInTheDocument();
  });

  it("renders custom avatar image when avatarUrl is provided", () => {
    const customTeacher = {
      name: "Prof. Carlos Santos",
      email: "carlos@escola.gov.br",
      role: "Professor Regente",
      school: "E.E. Maria Montessori",
      avatarUrl: "https://example.com/avatar.jpg",
    };

    render(<Header teacher={customTeacher} />);

    const img = screen.getByAltText(/foto de perfil de prof\. carlos santos/i);
    expect(img).toBeInTheDocument();
    expect(img).toHaveAttribute("src", "https://example.com/avatar.jpg");
  });

  it("closes menu when navigation link inside menu is clicked", async () => {
    const user = userEvent.setup();
    render(<Header />);

    await user.click(screen.getByRole("button", { name: /menu do usuário/i }));
    const navLink = screen.getByRole("menuitem", { name: /planos de aula adaptados/i });
    await user.click(navLink);

    expect(screen.queryByRole("menu")).not.toBeInTheDocument();
  });
});

